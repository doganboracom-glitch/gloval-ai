const dict: Partial<Record<Lang, BaseDict>> = { tr, en }

const cache = new Map<Lang, AdminDict>()

export function adminT(lang: Lang): AdminDict {
  let hit = cache.get(lang)
  if (!hit) {
    hit = { ...(dict[lang] ?? dict.tr!), pkg: packageCopy(lang) }
    cache.set(lang, hit)
  }
  return hit
}
