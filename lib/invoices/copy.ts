export function getInvoiceCopy(lang: string) {
  return copy[lang === 'tr' ? 'tr' : ('en' as Lang)]
}

export type InvoiceCopy = ReturnType<typeof getInvoiceCopy>

export function invoiceErrorText(c: InvoiceCopy, error: string): string {
  return (c.errors as Record<string, string>)[error] ?? c.errors.save_failed
}
