export type Dict = typeof dict.tr

/**
 * A dictionary for any locale other than tr/en never needs every key typed
 * out by hand: it only needs to override what it actually translates.
 * Anything it omits (down to individual leaf strings) is filled in from the
 * English dictionary at build time by `mergeWithEnglishFallback` below — this
 * is the "requested -> English -> default locale" fallback chain from the
 * i18n architecture spec. English is complete, so the chain never bottoms
 * out; a missing key can never crash a page.
 */
export type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends (infer U)[]
    ? U[]
    : T[K] extends object
      ? DeepPartial<T[K]>
      : T[K]
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function mergeWithEnglishFallback<T extends Record<string, unknown>>(
  base: T,
  overlay: DeepPartial<T> | undefined,
): T {
  if (!overlay) return base
  const result: Record<string, unknown> = { ...base }
  for (const key of Object.keys(overlay)) {
    const overlayValue = (overlay as Record<string, unknown>)[key]
    const baseValue = base[key]
    if (isPlainObject(overlayValue) && isPlainObject(baseValue)) {
      result[key] = mergeWithEnglishFallback(
        baseValue as Record<string, unknown>,
        overlayValue as DeepPartial<Record<string, unknown>>,
      )
    } else if (overlayValue !== undefined) {
      result[key] = overlayValue
    }
  }
  return result as T
}

const localeOverlays: Partial<Record<SupportedLocale, DeepPartial<Dict>>> = {
  fr: frOverlay,
  de: deOverlay,
  it: itOverlay,
  et: etOverlay,
  pl: plOverlay,
  es: esOverlay,
  pt: ptOverlay,
  ar: arOverlay,
  ru: ruOverlay,
  az: azOverlay,
}

export const dictionary: Record<Lang, Dict> = SUPPORTED_LOCALES.reduce(
  (acc, locale) => {
    if (locale === 'tr' || locale === 'en') {
      acc[locale] = dict[locale]
    } else {
      acc[locale] = mergeWithEnglishFallback(dict.en, localeOverlays[locale])
    }
    return acc
  },
  {} as Record<Lang, Dict>,
)
