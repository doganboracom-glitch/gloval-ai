/**
 * `Lang` is kept as the historical alias for `SupportedLocale` — dozens of
 * components already import `type { Lang }`. New code can use either name.
 */
export type Lang = SupportedLocale

export const DEFAULT_LANG: Lang = 'tr'

/**
 * Cookie that carries the visitor's language choice. It is written on the
 * client (LanguageProvider) and read on the server (app/layout.tsx) so that a
 * visitor who picks a language keeps it on every route — including full page
 * loads such as the post-login redirect into /dashboard — instead of falling
 * back to the default.
 */
export const LANG_COOKIE = 'gloval_lang'

export function normalizeLang(value: string | undefined | null): Lang | null {
  return matchLocaleTag(value ?? '')
}

/**
 * Reads a value out of a tr/en-only bilingual record (demo/showcase content,
 * admin copy, payment method labels, etc.) for any of the 12 platform
 * locales. That content is only fully translated for tr/en — every other
 * locale falls back to English, same as `getLocalized` in
 * `lib/content/types.ts` does for blog/FAQ content.
 */
export function pickLang<T>(value: { tr: T; en: T }, lang: Lang): T {
  return lang === 'tr' ? value.tr : value.en
}

/**
 * Narrows any of the 12 platform locales down to `'tr' | 'en'` for the
 * handful of components that are still bilingual-only (TryOnButton,
 * WebsitePreview editor, DemoPreviewFrame, admin billing labels). Same
 * fallback rule as `pickLang`: everything except `'tr'` reads as `'en'`.
 */
export function toBilingual(lang: Lang): 'tr' | 'en' {
  return lang === 'tr' ? 'tr' : 'en'
}

/**
 * Maps a browser `Accept-Language` header to one of the app's 12 supported
 * locales, for first-visit detection only (before any preference cookie
 * exists). Tags are read in the browser's own weighted order. Region/script
 * suffixes are folded to the base language (`en-GB` -> `en`, `fr-CA` -> `fr`,
 * `de-AT` -> `de`, `es-MX` -> `es`, `pt-BR` -> `pt`, `az-Latn-AZ` -> `az`).
 * Anything unsupported (e.g. `ja-JP`, `zh-CN`, `nl-NL`) falls through to the
 * next tag, and ultimately to `DEFAULT_LANG`.
 */
export function resolveLangFromAcceptLanguage(header: string | null | undefined): Lang {
  if (!header) return DEFAULT_LANG
  const tags = header
    .split(',')
    .map((part) => {
      const [tag, ...params] = part.trim().split(';')
      const qParam = params.find((p) => p.trim().startsWith('q='))
      const q = qParam ? Number.parseFloat(qParam.trim().slice(2)) : 1
      return { tag: tag.trim().toLowerCase(), q: Number.isFinite(q) ? q : 1 }
    })
    .sort((a, b) => b.q - a.q)

  for (const { tag } of tags) {
    const matched = matchLocaleTag(tag)
    if (matched) return matched
  }
  return DEFAULT_LANG
}

